func TestCrossLeagueIDOR_GetTransaction(t *testing.T) {
	leagueID := uuid.New()
	txnID := uuid.New()
	userID := uuid.New()

	repo := NewFakeRepository()
	txn := &Transaction{
		ID:       txnID,
		LeagueID: leagueID,
	}
	repo.transactions[txnID] = txn

	authz := &FakeAuthzChecker{allowManageLeague: true}
	svc := NewService(repo, authz)

	// Try with correct league
	retrieved, err := svc.GetTransaction(context.Background(), auth.Principal{UserID: userID}, leagueID, txnID)
	if err != nil {
		t.Errorf("GetTransaction with correct league failed: %v", err)
	}
	if retrieved == nil {
		t.Error("expected transaction")
	}

	// Try with wrong league
	wrongLeague := uuid.New()
	retrieved, err = svc.GetTransaction(context.Background(), auth.Principal{UserID: userID}, wrongLeague, txnID)
	if err == nil && retrieved != nil {
		t.Error("IDOR: should not retrieve transaction with wrong league")
	}
}

