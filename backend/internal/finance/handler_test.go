func TestCreateTransaction_Happy(t *testing.T) {
	leagueID := uuid.New()
	teamID := uuid.New()
	userID := uuid.New()

	repo := NewFakeRepository()
	authz := &FakeAuthzChecker{allowManageLeague: true}
	svc := NewService(repo, authz)

	req := &CreateTransactionRequest{
		TeamID:          &teamID,
		TransactionType: TransactionTypeYellowCardFine,
		Description:     "Test fine",
		Amount:          "100.00",
		IsIncome:        false,
	}

	txn, err := svc.CreateTransaction(context.Background(), auth.Principal{UserID: userID}, leagueID, req)
	if err != nil {
		t.Errorf("CreateTransaction failed: %v", err)
	}
	if txn == nil {
		t.Error("expected transaction, got nil")
	}
	if txn.Status != TransactionStatusPending {
		t.Errorf("expected status pending, got %v", txn.Status)
	}
}

