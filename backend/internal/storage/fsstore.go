// FSStore implements ObjectStore on the local filesystem (a Docker volume),
// for deployments without an S3 bucket.
//
// Public scopes (league/, team/, player/) are written under PublicDir, which
// the web server exposes read-only at PublicBaseURL. Every other scope goes
// to PrivateDir, which is never exposed: it is only reachable through
// short-lived HMAC-signed download URLs served by the API.
type FSStore struct {
	publicDir   string
	privateDir  string
	downloadURL string // absolute or root-relative URL of GET /storage/download
	signingKey  []byte
	now         func() time.Time
}

// NewFSStore creates the directories if needed.
func NewFSStore(publicDir, privateDir, downloadURL string, signingKey []byte) (*FSStore, error) {
	if len(signingKey) < 32 {
		return nil, errors.New("fsstore: signing key must be at least 32 bytes")
	}
	for _, d := range []string{publicDir, privateDir} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			return nil, fmt.Errorf("fsstore: %w", err)
		}
	}
	return &FSStore{publicDir: publicDir, privateDir: privateDir, downloadURL: downloadURL, signingKey: signingKey, now: time.Now}, nil
}

// path maps a validated key to its file. Keys are generated by the service
// and must match keyRegex, so they cannot contain "..", absolute paths or
// separators beyond the expected three segments.
func (s *FSStore) path(key string) (string, error) {
	scope, _, err := ParseKey(key)
	if err != nil {
		return "", err
	}
	root := s.privateDir
	if IsPublicScope(scope) {
		root = s.publicDir
	}
	p := filepath.Join(root, filepath.FromSlash(key))
	if !strings.HasPrefix(p, filepath.Clean(root)+string(filepath.Separator)) {
		return "", ErrInvalidKeyFormat
	}
	return p, nil
}

// Put implements ObjectStore. The file is written to a temp file and renamed,
// so readers never see partial uploads; more than size bytes is an error.
func (s *FSStore) Put(_ context.Context, key string, r io.Reader, size int64, _ string) (string, error) {
	p, err := s.path(key)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return "", fmt.Errorf("fsstore mkdir: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".upload-*")
	if err != nil {
		return "", fmt.Errorf("fsstore temp: %w", err)
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // no-op after a successful rename

	h := sha256.New()
	n, err := io.Copy(io.MultiWriter(tmp, h), io.LimitReader(r, size+1))
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return "", fmt.Errorf("fsstore write: %w", err)
	}
	if n > size {
		return "", errors.New("fsstore: body larger than declared size")
	}
	if err := os.Chmod(tmp.Name(), 0o640); err != nil {
		return "", fmt.Errorf("fsstore chmod: %w", err)
	}
	if err := os.Rename(tmp.Name(), p); err != nil {
		return "", fmt.Errorf("fsstore rename: %w", err)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Delete implements ObjectStore.
func (s *FSStore) Delete(_ context.Context, key string) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("fsstore delete: %w", err)
	}
	return nil
}

// List implements ObjectStore for prefixes of the form "{scope}/{uuid}/".
func (s *FSStore) List(_ context.Context, prefix string) ([]Object, error) {
	parts := strings.Split(strings.TrimSuffix(prefix, "/"), "/")
	if len(parts) != 2 || !ValidateScope(Scope(parts[0])) {
		return nil, ErrInvalidKeyFormat
	}
	root := s.privateDir
	if IsPublicScope(Scope(parts[0])) {
		root = s.publicDir
	}
	dir := filepath.Join(root, parts[0], filepath.Base(parts[1]))
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return []Object{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("fsstore list: %w", err)
	}
	out := make([]Object, 0, len(entries))
	for _, e := range entries {
		key := parts[0] + "/" + parts[1] + "/" + e.Name()
		if e.IsDir() || keyRegex.FindString(key) == "" {
			continue // skips temp files
		}
		info, err := e.Info()
		if err != nil {
			continue
		}
		out = append(out, Object{Key: key, Size: info.Size(), ContentType: mime.TypeByExtension(filepath.Ext(key)), CreatedAt: info.ModTime()})
		if len(out) == 1000 {
			break
		}
	}
	return out, nil
}

// PresignGet implements ObjectStore with an HMAC-signed API download URL.
func (s *FSStore) PresignGet(_ context.Context, key string, ttl time.Duration) (string, error) {
	if _, err := s.path(key); err != nil {
		return "", err
	}
	exp := s.now().Add(ttl).Unix()
	q := url.Values{"key": {key}, "exp": {strconv.FormatInt(exp, 10)}, "sig": {s.sign(key, exp)}}
	return s.downloadURL + "?" + q.Encode(), nil
}

func (s *FSStore) sign(key string, exp int64) string {
	m := hmac.New(sha256.New, s.signingKey)
	fmt.Fprintf(m, "%s\n%d", key, exp)
	return hex.EncodeToString(m.Sum(nil))
}

// ErrBadSignature is returned for invalid or expired download links.
var ErrBadSignature = errors.New("invalid or expired link")

// Open verifies a signed download link and opens the file.
func (s *FSStore) Open(key, expRaw, sig string) (*os.File, error) {
	exp, err := strconv.ParseInt(expRaw, 10, 64)
	if err != nil || s.now().Unix() > exp {
		return nil, ErrBadSignature
	}
	if !hmac.Equal([]byte(sig), []byte(s.sign(key, exp))) {
		return nil, ErrBadSignature
	}
	p, err := s.path(key)
	if err != nil {
		return nil, ErrBadSignature
	}
	return os.Open(p) // #nosec G304 -- path derived from a validated, signed key
}

// DeriveKey derives a purpose-specific key from a master secret, so the
// download signing key differs from the JWT key without a new setting.
func DeriveKey(secret, purpose string) []byte {
	m := hmac.New(sha256.New, []byte(secret))
	m.Write([]byte(purpose))
	return m.Sum(nil)
}
