// Package knowledge is the knowledge base embedding feature: generate vector
// embeddings for league content (standings, match results, jornadas) and save
// them to the database for use in the AI RAG system.
package knowledge

import (
	"context"
	"time"

	"github.com/google/uuid"
)

// KnowledgeBase represents a row in public.league_knowledge_base.
type KnowledgeBase struct {
	ID              uuid.UUID              `json:"id"`
	LeagueID        uuid.UUID              `json:"league_id"`
	TournamentID    *uuid.UUID             `json:"tournament_id,omitempty"`
	ContentType     string                 `json:"content_type"`
	ContentText     string                 `json:"content_text"`
	Metadata        map[string]interface{} `json:"metadata,omitempty"`
	Embedding       []float32              `json:"-"` // Don't return embedding to client
	ValidFrom       time.Time              `json:"valid_from"`
	ValidUntil      *time.Time             `json:"valid_until,omitempty"`
	IsAutoGenerated bool                   `json:"is_auto_generated"`
	CreatedAt       time.Time              `json:"created_at"`
	UpdatedAt       time.Time              `json:"updated_at"`
	MatchID         *uuid.UUID             `json:"match_id,omitempty"`
}

// CreateEmbeddingRequest is the payload for creating a knowledge entry with embedding.
type CreateEmbeddingRequest struct {
	LeagueID     uuid.UUID              `json:"league_id"`
	TournamentID *uuid.UUID             `json:"tournament_id,omitempty"`
	ContentType  string                 `json:"content_type"`
	ContentText  string                 `json:"content_text"`
	Metadata     map[string]interface{} `json:"metadata,omitempty"`
	MatchID      *uuid.UUID             `json:"match_id,omitempty"`
}

// Validate returns validation errors for CreateEmbeddingRequest.
func (r CreateEmbeddingRequest) Validate() map[string]string {
	errors := make(map[string]string)
	if r.LeagueID == uuid.Nil {
		errors["league_id"] = "Requerido"
	}
	if r.ContentType == "" {
		errors["content_type"] = "Requerido"
	} else if !isValidContentType(r.ContentType) {
		errors["content_type"] = "Tipo inválido"
	}
	if r.ContentText == "" {
		errors["content_text"] = "Requerido"
	} else if len(r.ContentText) > 8000 {
		errors["content_text"] = "Máximo 8000 caracteres"
	}
	if len(r.Metadata) > 20 {
		errors["metadata"] = "Máximo 20 claves"
	}
	return errors
}

// TriggerEmbeddingRequest is the payload for trigger-based embedding generation.
type TriggerEmbeddingRequest struct {
	TriggerType  string     `json:"trigger_type"`
	LeagueID     uuid.UUID  `json:"league_id"`
	TournamentID uuid.UUID  `json:"tournament_id"`
	MatchID      *uuid.UUID `json:"match_id,omitempty"`
	Round        *int       `json:"round,omitempty"`
}

// Validate returns validation errors for TriggerEmbeddingRequest.
func (r TriggerEmbeddingRequest) Validate() map[string]string {
	errors := make(map[string]string)
	if !isValidTriggerType(r.TriggerType) {
		errors["trigger_type"] = "Tipo inválido"
	}
	if r.LeagueID == uuid.Nil {
		errors["league_id"] = "Requerido"
	}
	if r.TournamentID == uuid.Nil {
		errors["tournament_id"] = "Requerido"
	}
	if r.TriggerType == "match_result_update" && (r.MatchID == nil || *r.MatchID == uuid.Nil) {
		errors["match_id"] = "Requerido para match_result_update"
	}
	if r.TriggerType == "jornada_update" && r.Round == nil {
		errors["round"] = "Requerido para jornada_update"
	}
	return errors
}

// Valid content_type values from database constraint
var validContentTypes = map[string]bool{
	"jornada":           true,
	"tabla_posiciones":  true,
	"suspensiones":      true,
	"resultados":        true,
	"resultado_partido": true,
	"estadisticas":      true,
	"proximo_partido":   true,
}

func isValidContentType(ct string) bool {
	return validContentTypes[ct]
}

// Valid trigger_type values
var validTriggerTypes = map[string]bool{
	"jornada_update":      true,
	"match_result_update": true,
	"standings_update":    true,
}

func isValidTriggerType(tt string) bool {
	return validTriggerTypes[tt]
}

// Repository is the persistence contract the service depends on.
type Repository interface {
	// Create inserts a new knowledge entry with the given embedding vector.
	// It returns the created entry (with ID and timestamps).
	Create(ctx context.Context, req CreateEmbeddingRequest, embedding []float32) (KnowledgeBase, error)

	// GenerateStandingsContent generates content for standings and upserts to knowledge base.
	// Returns the knowledge_base row id and content_text.
	GenerateStandingsContent(ctx context.Context, leagueID, tournamentID uuid.UUID) (uuid.UUID, string, error)

	// GenerateMatchResultContent builds the match result text via SQL and returns its row.
	GenerateMatchResultContent(ctx context.Context, matchID uuid.UUID) (uuid.UUID, string, error)

	// GenerateJornadaContent builds the round schedule text via SQL and returns its row.
	GenerateJornadaContent(ctx context.Context, leagueID, tournamentID uuid.UUID, round int) (uuid.UUID, string, error)

	// ValidateTournamentBelongsToLeague checks that tournament_id belongs to league_id.
	ValidateTournamentBelongsToLeague(ctx context.Context, leagueID, tournamentID uuid.UUID) error

	// ValidateMatchBelongsToTournament checks that match_id belongs to tournament_id.
	ValidateMatchBelongsToTournament(ctx context.Context, matchID, tournamentID uuid.UUID) error

	// UpdateEmbedding updates the embedding vector for a knowledge entry.
	UpdateEmbedding(ctx context.Context, knowledgeID uuid.UUID, embedding []float32) error
}

// Embedder generates vector embeddings for text content.
type Embedder interface {
	// Embed generates embeddings for the given texts and returns their vectors.
	// Each text corresponds to one vector in the output slice.
	// Returns an error if the API call fails or returns invalid data.
	Embed(ctx context.Context, texts []string) ([][]float32, error)
}
