// PGRepository implements Repository with pgx. Every query is parameterized.
type PGRepository struct {
	db database.Querier
}

// NewPGRepository builds a PostgreSQL-backed repository.
func NewPGRepository(db database.Querier) *PGRepository {
	return &PGRepository{db: db}
}

// Create inserts a new knowledge entry with the given embedding vector.
// It returns the created entry with ID and timestamps.
func (r *PGRepository) Create(ctx context.Context, req CreateEmbeddingRequest, embedding []float32) (KnowledgeBase, error) {
	// Convert embedding slice to pgvector text format: [0.1,0.2,...]
	embeddingText := embeddingToVector(embedding)

	// Marshal metadata to JSON
	metadataJSON := "{}"
	if req.Metadata != nil {
		b, err := json.Marshal(req.Metadata)
		if err != nil {
			return KnowledgeBase{}, fmt.Errorf("marshal metadata: %w", err)
		}
		metadataJSON = string(b)
	}

	const q = `
		INSERT INTO public.league_knowledge_base (
			league_id, tournament_id, content_type, content_text,
			metadata, embedding, is_auto_generated, match_id
		) VALUES (
			$1, $2, $3, $4,
			$5::jsonb, $6::vector, $7, $8
		)
		RETURNING
			id, league_id, tournament_id, content_type, content_text,
			metadata, valid_from, valid_until, is_auto_generated,
			created_at, updated_at, match_id
	`

	var kb KnowledgeBase
	var metadataBytes []byte
	var validUntil *time.Time

	err := r.db.QueryRow(ctx, q,
		req.LeagueID, req.TournamentID, req.ContentType, req.ContentText,
		metadataJSON, embeddingText, false, req.MatchID,
	).Scan(
		&kb.ID, &kb.LeagueID, &kb.TournamentID, &kb.ContentType, &kb.ContentText,
		&metadataBytes, &kb.ValidFrom, &validUntil, &kb.IsAutoGenerated,
		&kb.CreatedAt, &kb.UpdatedAt, &kb.MatchID,
	)

	if err != nil {
		return KnowledgeBase{}, fmt.Errorf("insert knowledge base: %w", err)
	}

	if validUntil != nil {
		kb.ValidUntil = validUntil
	}

	if err := json.Unmarshal(metadataBytes, &kb.Metadata); err != nil {
		return KnowledgeBase{}, fmt.Errorf("unmarshal metadata: %w", err)
	}

	if kb.Metadata == nil {
		kb.Metadata = make(map[string]interface{})
	}

	return kb, nil
}

// embeddingToVector converts a float32 slice to pgvector text format: [0.1,0.2,...]
func embeddingToVector(embedding []float32) string {
	if len(embedding) == 0 {
		return "[]"
	}
	sb := strings.Builder{}
	sb.WriteRune('[')
	for i, v := range embedding {
		if i > 0 {
			sb.WriteRune(',')
		}
		sb.WriteString(fmt.Sprintf("%g", v))
	}
	sb.WriteRune(']')
	return sb.String()
}

// parseVectorEmbedding parses pgvector text format to float32 slice.
// Format: [0.1,0.2,...]
func parseVectorEmbedding(s string) ([]float32, error) {
	// Trim brackets
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "[") && strings.HasSuffix(s, "]") {
		s = s[1 : len(s)-1]
	}

	if s == "" {
		return []float32{}, nil
	}

	parts := strings.Split(s, ",")
	result := make([]float32, len(parts))

	for i, part := range parts {
		var v float64
		if _, err := fmt.Sscanf(strings.TrimSpace(part), "%v", &v); err != nil {
			return nil, fmt.Errorf("parse vector element %d: %w", i, err)
		}
		result[i] = float32(v)
	}

	return result, nil
}

// GenerateStandingsContent generates standings content and upserts to knowledge base.
func (r *PGRepository) GenerateStandingsContent(ctx context.Context, leagueID, tournamentID uuid.UUID) (uuid.UUID, string, error) {
	// Get standings data from team_stats
	const q = `
		SELECT ts.team_id, ts.matches_played, ts.matches_won, ts.matches_drawn,
		       ts.matches_lost, ts.goals_for, ts.goals_against, ts.goal_difference,
		       ts.points, ts.points_adjustment, ts.adjustment_reason, t.name as team_name
		FROM public.team_stats ts
		JOIN public.teams t ON t.id = ts.team_id
		WHERE ts.tournament_id = $1
		ORDER BY (ts.points + COALESCE(ts.points_adjustment, 0)) DESC,
		         ts.goal_difference DESC, ts.goals_for DESC
	`

	rows, err := r.db.Query(ctx, q, tournamentID)
	if err != nil {
		return uuid.Nil, "", fmt.Errorf("query standings: %w", err)
	}
	defer rows.Close()

	type standingsRow struct {
		teamID           uuid.UUID
		matchesPlayed    int
		matchesWon       int
		matchesDrawn     int
		matchesLost      int
		goalsFor         int
		goalsAgainst     int
		goalDifference   int
		points           int
		pointsAdjustment *int
		adjustmentReason *string
		teamName         string
	}

	var standings []standingsRow
	for rows.Next() {
		var s standingsRow
		if err := rows.Scan(&s.teamID, &s.matchesPlayed, &s.matchesWon, &s.matchesDrawn,
			&s.matchesLost, &s.goalsFor, &s.goalsAgainst, &s.goalDifference,
			&s.points, &s.pointsAdjustment, &s.adjustmentReason, &s.teamName); err != nil {
			return uuid.Nil, "", fmt.Errorf("scan standing: %w", err)
		}
		standings = append(standings, s)
	}

	if err := rows.Err(); err != nil {
		return uuid.Nil, "", fmt.Errorf("iterate standings: %w", err)
	}

	// Get tournament and league names
	const nameQ = `
		SELECT t.name, l.name FROM public.tournaments t
		JOIN public.leagues l ON l.id = t.league_id
		WHERE t.id = $1
	`
	var tournamentName, leagueName string
	if err := r.db.QueryRow(ctx, nameQ, tournamentID).Scan(&tournamentName, &leagueName); err != nil {
		leagueName, tournamentName = "Liga", "Torneo"
	}

	// Generate content text (matching legacy format)
	var content strings.Builder
	content.WriteString(fmt.Sprintf("📊 TABLA DE POSICIONES - %s - %s\n\n", leagueName, tournamentName))
	content.WriteString("Pos | Equipo | PJ | PG | PE | PP | GF | GC | DIF | PTS\n")
	content.WriteString("---|--------|----|----|----|----|----|----|-----|----\n")

	for i, s := range standings {
		totalPoints := s.points
		if s.pointsAdjustment != nil {
			totalPoints += *s.pointsAdjustment
		}
		adjustment := ""
		if s.pointsAdjustment != nil && *s.pointsAdjustment != 0 {
			sign := "+"
			if *s.pointsAdjustment < 0 {
				sign = ""
			}
			adjustment = fmt.Sprintf(" (%s%d)", sign, *s.pointsAdjustment)
		}
		diffSign := ""
		if s.goalDifference > 0 {
			diffSign = "+"
		}
		content.WriteString(fmt.Sprintf("%d | %s | %d | %d | %d | %d | %d | %d | %s%d | %d%s\n",
			i+1, s.teamName, s.matchesPlayed, s.matchesWon, s.matchesDrawn,
			s.matchesLost, s.goalsFor, s.goalsAgainst, diffSign, s.goalDifference, totalPoints, adjustment))
	}

	if len(standings) > 0 {
		leader := standings[0]
		leaderPoints := leader.points
		if leader.pointsAdjustment != nil {
			leaderPoints += *leader.pointsAdjustment
		}
		content.WriteString(fmt.Sprintf("\n🏆 Líder: %s con %d puntos", leader.teamName, leaderPoints))
	}

	contentText := content.String()

	// Upsert to knowledge base
	// No unique constraint exists on (league, tournament, content_type), so
	// update the newest row if present, otherwise insert one.
	const upsertQ = `
		WITH target AS (
			SELECT id FROM public.league_knowledge_base
			WHERE league_id = $1 AND tournament_id = $2 AND content_type = $3
			ORDER BY created_at DESC LIMIT 1
		), upd AS (
			UPDATE public.league_knowledge_base k
			SET content_text = $4, metadata = $5::jsonb, updated_at = NOW()
			FROM target WHERE k.id = target.id
			RETURNING k.id
		), ins AS (
			INSERT INTO public.league_knowledge_base (
				league_id, tournament_id, content_type, content_text, metadata, is_auto_generated
			)
			SELECT $1, $2, $3, $4, $5::jsonb, true
			WHERE NOT EXISTS (SELECT 1 FROM target)
			RETURNING id
		)
		SELECT id FROM upd UNION ALL SELECT id FROM ins
	`

	metadata := fmt.Sprintf(`{"generated_at": "%s", "teams_count": %d}`,
		time.Now().Format(time.RFC3339), len(standings))

	var kbID uuid.UUID
	if err := r.db.QueryRow(ctx, upsertQ, leagueID, tournamentID, "tabla_posiciones", contentText, metadata).Scan(&kbID); err != nil {
		return uuid.Nil, "", fmt.Errorf("upsert standings: %w", err)
	}

	return kbID, contentText, nil
}

// GenerateMatchResultContent builds the match summary with the SQL function
// generate_match_result_content and stores it as the match's
// 'resultado_partido' row (updating the newest one if it already exists).
// It does not rely on the match-finish trigger having written the row.
func (r *PGRepository) GenerateMatchResultContent(ctx context.Context, matchID uuid.UUID) (uuid.UUID, string, error) {
	var content string
	if err := r.db.QueryRow(ctx, `SELECT public.generate_match_result_content($1)`, matchID).Scan(&content); err != nil {
		return uuid.Nil, "", fmt.Errorf("generate match result content: %w", err)
	}
	if content == "" {
		// The function returns '' when the match is missing or not finished.
		return uuid.Nil, "", httpx.ErrNotFound.Wrap(errors.New("match not finished"))
	}

	const upsertQ = `
		WITH target AS (
			SELECT id FROM public.league_knowledge_base
			WHERE match_id = $1 AND content_type = 'resultado_partido'
			ORDER BY created_at DESC LIMIT 1
		), upd AS (
			UPDATE public.league_knowledge_base k
			SET content_text = $2, updated_at = NOW()
			FROM target WHERE k.id = target.id
			RETURNING k.id
		), ins AS (
			INSERT INTO public.league_knowledge_base (
				league_id, tournament_id, match_id, content_type, content_text,
				metadata, is_auto_generated, valid_from
			)
			SELECT t.league_id, t.id, m.id, 'resultado_partido', $2,
			       jsonb_build_object('match_id', m.id, 'home_score', m.home_score, 'away_score', m.away_score),
			       true, m.match_date
			FROM public.matches m JOIN public.tournaments t ON t.id = m.tournament_id
			WHERE m.id = $1 AND NOT EXISTS (SELECT 1 FROM target)
			RETURNING id
		)
		SELECT id FROM upd UNION ALL SELECT id FROM ins`

	var id uuid.UUID
	if err := r.db.QueryRow(ctx, upsertQ, matchID, content).Scan(&id); err != nil {
		return uuid.Nil, "", fmt.Errorf("store match result content: %w", err)
	}
	return id, content, nil
}

// GenerateJornadaContent runs insert_jornada_to_knowledge_base and returns
// the newest 'jornada' row for that round.
func (r *PGRepository) GenerateJornadaContent(ctx context.Context, leagueID, tournamentID uuid.UUID, round int) (uuid.UUID, string, error) {
	if _, err := r.db.Exec(ctx, `SELECT public.insert_jornada_to_knowledge_base($1, $2, $3)`, leagueID, tournamentID, round); err != nil {
		return uuid.Nil, "", fmt.Errorf("generate jornada content: %w", err)
	}
	return r.latestContent(ctx, `
		SELECT id, content_text FROM public.league_knowledge_base
		WHERE league_id = $1 AND tournament_id = $2 AND content_type = 'jornada'
		  AND metadata->>'round' = ($3::int)::text AND content_text IS NOT NULL
		ORDER BY created_at DESC LIMIT 1`, leagueID, tournamentID, round)
}

func (r *PGRepository) latestContent(ctx context.Context, q string, args ...any) (uuid.UUID, string, error) {
	var id uuid.UUID
	var content string
	err := r.db.QueryRow(ctx, q, args...).Scan(&id, &content)
	if database.IsNoRows(err) {
		return uuid.Nil, "", httpx.ErrNotFound.Wrap(errors.New("generated content not found"))
	}
	if err != nil {
		return uuid.Nil, "", fmt.Errorf("load generated content: %w", err)
	}
	return id, content, nil
}

// ValidateTournamentBelongsToLeague returns httpx.ErrNotFound unless the
// tournament exists inside the league.
func (r *PGRepository) ValidateTournamentBelongsToLeague(ctx context.Context, leagueID, tournamentID uuid.UUID) error {
	return r.exists(ctx, `SELECT 1 FROM public.tournaments WHERE id = $1 AND league_id = $2`, tournamentID, leagueID)
}

// ValidateMatchBelongsToTournament returns httpx.ErrNotFound unless the match
// exists inside the tournament.
func (r *PGRepository) ValidateMatchBelongsToTournament(ctx context.Context, matchID, tournamentID uuid.UUID) error {
	return r.exists(ctx, `SELECT 1 FROM public.matches WHERE id = $1 AND tournament_id = $2`, matchID, tournamentID)
}

func (r *PGRepository) exists(ctx context.Context, q string, args ...any) error {
	var one int
	err := r.db.QueryRow(ctx, q, args...).Scan(&one)
	if database.IsNoRows(err) {
		return httpx.ErrNotFound
	}
	if err != nil {
		return fmt.Errorf("check ownership: %w", err)
	}
	return nil
}

// UpdateEmbedding updates the embedding for a knowledge entry.
func (r *PGRepository) UpdateEmbedding(ctx context.Context, knowledgeID uuid.UUID, embedding []float32) error {
	embeddingText := embeddingToVector(embedding)
	const q = `UPDATE public.league_knowledge_base SET embedding = $1::vector, updated_at = NOW() WHERE id = $2`
	if _, err := r.db.Exec(ctx, q, embeddingText, knowledgeID); err != nil {
		return fmt.Errorf("update embedding: %w", err)
	}
	return nil
}
