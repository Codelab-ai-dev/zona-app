func TestCreateEmbedding(t *testing.T) {
	leagueID := uuid.New()
	tournamentID := uuid.New()
	userID := uuid.New()

	tests := []struct {
		name       string
		principal  *auth.Principal
		body       string
		authz      *fakeAuthz
		wantStatus int
		wantError  bool
	}{
		{
			name:       "anonymous is rejected",
			principal:  nil,
			body:       `{"league_id":"` + leagueID.String() + `","content_type":"test","content_text":"Hello world"}`,
			authz:      &fakeAuthz{canManage: true},
			wantStatus: http.StatusUnauthorized,
			wantError:  true,
		},
		{
			name:       "authenticated without permission is rejected",
			principal:  &auth.Principal{UserID: userID, Role: auth.RoleTeamOwner, IsActive: true},
			body:       `{"league_id":"` + leagueID.String() + `","content_type":"test","content_text":"Hello world"}`,
			authz:      &fakeAuthz{canManage: false},
			wantStatus: http.StatusForbidden,
			wantError:  true,
		},
		{
			name:       "missing content_text is rejected",
			principal:  &auth.Principal{UserID: userID, Role: auth.RoleLeagueAdmin, IsActive: true},
			body:       `{"league_id":"` + leagueID.String() + `","content_type":"test"}`,
			authz:      &fakeAuthz{canManage: true},
			wantStatus: http.StatusUnprocessableEntity,
			wantError:  true,
		},
		{
			name:       "content_text too long is rejected",
			principal:  &auth.Principal{UserID: userID, Role: auth.RoleLeagueAdmin, IsActive: true},
			body:       `{"league_id":"` + leagueID.String() + `","content_type":"test","content_text":"` + strings.Repeat("x", 8001) + `"}`,
			authz:      &fakeAuthz{canManage: true},
			wantStatus: http.StatusUnprocessableEntity,
			wantError:  true,
		},
		{
			name:       "authenticated with permission succeeds",
			principal:  &auth.Principal{UserID: userID, Role: auth.RoleLeagueAdmin, IsActive: true},
			body:       `{"league_id":"` + leagueID.String() + `","tournament_id":"` + tournamentID.String() + `","content_type":"tabla_posiciones","content_text":"Position table content"}`,
			authz:      &fakeAuthz{canManage: true},
			wantStatus: http.StatusCreated,
			wantError:  false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			repo := &fakeRepository{entries: make(map[uuid.UUID]KnowledgeBase)}
			emb := &fakeEmbedder{}

			r := chi.NewRouter()
			r.With(auth.RequireAuth).Post("/knowledge/embeddings", func(w http.ResponseWriter, r *http.Request) {
				if tt.authz.canManage != true && tt.principal != nil && tt.principal.Role != auth.RoleSuperAdmin {
					httpx.WriteError(w, r, httpx.ErrForbidden)
					return
				}
				var req CreateEmbeddingRequest
				if err := httpx.DecodeJSON(w, r, &req); err != nil {
					httpx.WriteError(w, r, err)
					return
				}
				caller, _ := auth.FromContext(r.Context())
				if err := tt.authz.CanManageLeague(r.Context(), caller, req.LeagueID); err != nil {
					httpx.WriteError(w, r, err)
					return
				}
				embeddings, _ := emb.Embed(r.Context(), []string{req.ContentText})
				kb, _ := repo.Create(r.Context(), req, embeddings[0])
				httpx.JSON(w, http.StatusCreated, kb)
			})

			req := httptest.NewRequest(http.MethodPost, "/knowledge/embeddings", strings.NewReader(tt.body))
			req.Header.Set("Content-Type", "application/json")
			if tt.principal != nil {
				req = req.WithContext(auth.WithPrincipal(req.Context(), *tt.principal))
			}
			rec := httptest.NewRecorder()
			r.ServeHTTP(rec, req)

			if rec.Code != tt.wantStatus {
				t.Fatalf("status = %d, want %d; body = %s", rec.Code, tt.wantStatus, rec.Body)
			}

			if !tt.wantError && tt.wantStatus == http.StatusCreated {
				var got KnowledgeBase
				if err := json.NewDecoder(rec.Body).Decode(&got); err != nil {
					t.Fatal(err)
				}
				if got.LeagueID != leagueID {
					t.Errorf("league_id = %s, want %s", got.LeagueID, leagueID)
				}
			}
		})
	}
}
