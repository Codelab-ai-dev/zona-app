import 'package:equatable/equatable.dart';

import 'finance_enums.dart';

/// Finance Transaction Entity
/// A charge, fine, expense or income of a league.
class FinanceTransactionEntity extends Equatable {
  final String id;
  final String leagueId;
  final String? tournamentId;
  final String? teamId;
  final String? playerId;
  final String? matchId;
  final TransactionType transactionType;
  final String description;
  final String? notes;
  final double amount;
  final double amountPaid;
  final bool isIncome;
  final TransactionStatus status;
  final DateTime? transactionDate;
  final DateTime? dueDate;
  final DateTime? paidAt;
  final PaymentMethod? paymentMethod;
  final String? paymentReference;
  final String? receiptNumber;
  final bool autoGenerated;
  final String? cancellationReason;
  final DateTime? createdAt;
  final DateTime? updatedAt;

  /// Team name (resolved from the league's team balances; the API row has no name).
  final String? teamName;
  final String? playerName;
  final int? playerNumber;

  const FinanceTransactionEntity({
    required this.id,
    required this.leagueId,
    this.tournamentId,
    this.teamId,
    this.playerId,
    this.matchId,
    required this.transactionType,
    required this.description,
    this.notes,
    required this.amount,
    this.amountPaid = 0.0,
    this.isIncome = false,
    this.status = TransactionStatus.pending,
    this.transactionDate,
    this.dueDate,
    this.paidAt,
    this.paymentMethod,
    this.paymentReference,
    this.receiptNumber,
    this.autoGenerated = false,
    this.cancellationReason,
    this.createdAt,
    this.updatedAt,
    this.teamName,
    this.playerName,
    this.playerNumber,
  });

  @override
  List<Object?> get props => [
    id,
    leagueId,
    tournamentId,
    teamId,
    playerId,
    matchId,
    transactionType,
    description,
    notes,
    amount,
    amountPaid,
    isIncome,
    status,
    transactionDate,
    dueDate,
    paidAt,
    paymentMethod,
    paymentReference,
    receiptNumber,
    autoGenerated,
    cancellationReason,
    createdAt,
    updatedAt,
    teamName,
    playerName,
    playerNumber,
  ];

  /// Amount still pending payment
  double get amountPending {
    final pending = amount - amountPaid;
    return pending < 0 ? 0 : pending;
  }

  /// Whether the transaction is fully paid
  bool get isPaid => status == TransactionStatus.paid;

  /// Whether pay / cancel are still allowed
  bool get isOpen => status.isOpen;

  /// Whether the transaction is overdue
  bool get isOverdue {
    if (status == TransactionStatus.overdue) return true;
    if (dueDate == null || !status.isOpen) return false;
    final today = DateTime.now();
    return DateTime(today.year, today.month, today.day).isAfter(dueDate!);
  }

  FinanceTransactionEntity copyWith({String? teamName}) {
    return FinanceTransactionEntity(
      id: id,
      leagueId: leagueId,
      tournamentId: tournamentId,
      teamId: teamId,
      playerId: playerId,
      matchId: matchId,
      transactionType: transactionType,
      description: description,
      notes: notes,
      amount: amount,
      amountPaid: amountPaid,
      isIncome: isIncome,
      status: status,
      transactionDate: transactionDate,
      dueDate: dueDate,
      paidAt: paidAt,
      paymentMethod: paymentMethod,
      paymentReference: paymentReference,
      receiptNumber: receiptNumber,
      autoGenerated: autoGenerated,
      cancellationReason: cancellationReason,
      createdAt: createdAt,
      updatedAt: updatedAt,
      teamName: teamName ?? this.teamName,
      playerName: playerName,
      playerNumber: playerNumber,
    );
  }
}
